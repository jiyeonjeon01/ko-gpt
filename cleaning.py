"""문서 품질 필터, 개인정보 치환, 근사 중복(MinHash) (설계안 v0.2 7-2절)

필터는 탈락 사유 문자열을 돌려준다 (통과하면 None). 사유별 개수를 통계로 남기기 위함이다.
"""

import hashlib
import re
from urllib.parse import urlparse

import numpy as np

# ---- 개인정보 → 일반 텍스트 자리표시 (특수 토큰이 아니다) ----

PII_PATTERNS = [
    ("[EMAIL]", re.compile(r"[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}")),
    ("[ID_NUMBER]", re.compile(r"(?<!\d)\d{6}-[1-4]\d{6}(?!\d)")),  # 주민등록번호 형식
    ("[PHONE]", re.compile(r"(?<!\d)(?:01[016789]|0\d{1,2})[-. ]\d{3,4}[-. ]\d{4}(?!\d)")),
]


def mask_pii(text: str) -> tuple[str, dict[str, int]]:
    counts = {}
    for placeholder, pattern in PII_PATTERNS:
        text, n = pattern.subn(placeholder, text)
        if n:
            counts[placeholder] = n
    return text, counts


# ---- 품질 필터 ----

_HANGUL = re.compile(r"[가-힣]")
_LETTER = re.compile(r"[^\W\d_]")
# 도박·성인·스팸 광고에 자주 나오는 말. 한 문서에 서로 다른 말이 SPAM_MIN_HITS개 이상이면 제외
SPAM_TERMS = ["카지노", "바카라", "토토사이트", "먹튀", "슬롯머신", "출장안마", "출장마사지", "조건만남", "성인용품",
              "비아그라", "홀덤", "파워볼", "사설토토", "대출문의", "작업대출", "스포츠토토"]
SPAM_MIN_HITS = 2
WIKI_MIRROR_DOMAINS = ("wikipedia.org", "wikiwand.com", "wikimedia.org")
_SENTENCE_END = re.compile(r"[.!?。…\"'”’)\]다요죠음함됨]$")


def hangul_ratio(text: str) -> float:
    letters = len(_LETTER.findall(text))
    return len(_HANGUL.findall(text)) / letters if letters else 0.0


def duplicate_line_ratio(text: str) -> float:
    lines = [ln for ln in text.split("\n") if ln.strip()]
    if not lines:
        return 1.0
    return 1 - len(set(lines)) / len(lines)


def is_wiki_mirror(url: str | None) -> bool:
    if not url:
        return False
    host = urlparse(url).netloc.lower()
    return any(host == d or host.endswith("." + d) for d in WIKI_MIRROR_DOMAINS)


def filter_ko_web(text: str, url: str | None) -> str | None:
    if is_wiki_mirror(url):
        return "wiki_mirror_url"
    if len(text) < 200:
        return "too_short"
    if hangul_ratio(text) < 0.5:
        return "low_hangul_ratio"
    if duplicate_line_ratio(text) > 0.3:
        return "repeated_lines"
    if sum(term in text for term in SPAM_TERMS) >= SPAM_MIN_HITS:
        return "spam_terms"
    lines = [ln.strip() for ln in text.split("\n") if ln.strip()]
    if len(lines) >= 5 and sum(bool(_SENTENCE_END.search(ln)) for ln in lines) / len(lines) < 0.2:
        return "few_sentence_endings"  # 목록·메뉴 위주의 페이지
    return None


def filter_wiki(text: str, title: str | None, lang: str) -> str | None:
    if len(text) < 300:
        return "too_short"
    t = title or ""
    if lang == "ko" and ("동음이의" in t or "다음과 같은 뜻이 있다" in text[:200]):
        return "disambiguation"
    if lang == "en" and ("(disambiguation)" in t or "may refer to:" in text[:300]):
        return "disambiguation"
    if t.startswith(("목록", "List of")):
        return "list_page"
    return None


def filter_pdf(text: str) -> str | None:
    if len(text) < 200:
        return "too_short"
    letters = len(_LETTER.findall(text))
    if letters / max(len(text), 1) < 0.5:
        return "low_letter_ratio"  # 표·숫자 잔해
    if hangul_ratio(text) < 0.3:
        return "low_hangul_ratio"
    return None


def filter_length_only(text: str, min_chars: int = 200) -> str | None:
    return "too_short" if len(text) < min_chars else None


AUTOGEN = re.compile(r"auto-?generated|do not edit|generated by", re.IGNORECASE)


def filter_code(text: str) -> str | None:
    if len(text) < 50:
        return "too_short"
    if len(text) > 100_000:
        return "too_long"
    if max((len(ln) for ln in text.split("\n")), default=0) > 1000:
        return "long_line"
    if AUTOGEN.search(text[:500]):
        return "autogenerated"
    return None


def text_digest(text: str) -> bytes:
    return hashlib.sha256(text.encode("utf-8")).digest()[:16]


# ---- MinHash (문자 5-gram, numpy 벡터화) ----

class MinHasher:
    """순열마다 64비트 multiply-xorshift 해시의 최솟값.

    (a·s + b) mod (2^61 - 1)에 작은 a와 32비트 s를 쓰면 값이 소수를 넘지 않아 s에 대해 단조 증가하고,
    모든 순열이 가장 작은 shingle을 고르게 된다 (Phase 0 첫 측정에서 실제 Jaccard 0.03인 쌍을 0.9로 추정한 버그).
    여기서는 64비트 곱셈의 자연스러운 넘침(mod 2^64)과 상위 비트 섞기로 순열을 흉내 낸다.
    """

    def __init__(self, num_perm: int = 64, shingle: int = 5, max_chars: int = 3000, seed: int = 1):
        rng = np.random.default_rng(seed)
        self.a = rng.integers(0, 2**63, num_perm, dtype=np.uint64) * np.uint64(2) + np.uint64(1)  # 홀수
        self.b = rng.integers(0, 2**63, num_perm, dtype=np.uint64)
        self.shingle, self.max_chars = shingle, max_chars

    def shingles(self, text: str) -> np.ndarray:
        """문자 n-gram을 32비트 해시로 (중복 제거). 앞 max_chars자만 본다."""
        codes = np.frombuffer(text[: self.max_chars].encode("utf-32-le"), dtype=np.uint32).astype(np.uint64)
        n = self.shingle
        if len(codes) < n:
            codes = np.pad(codes, (0, n - len(codes)))
        h = np.zeros(len(codes) - n + 1, dtype=np.uint64)
        for i in range(n):
            h = (h * np.uint64(1_000_003) + codes[i : len(codes) - n + 1 + i]) & np.uint64(0xFFFFFFFF)
        return np.unique(h)

    def signature(self, text: str) -> np.ndarray:
        s = self.shingles(text)
        with np.errstate(over="ignore"):
            x = np.outer(self.a, s) + self.b[:, None]  # mod 2^64
            x ^= x >> np.uint64(29)
            x *= np.uint64(0xBF58476D1CE4E5B9)
            x ^= x >> np.uint64(32)
        return x.min(axis=1)


def lsh_candidate_pairs(signatures: np.ndarray, bands: int) -> set[tuple[int, int]]:
    """signatures: (N, num_perm). 밴드가 하나라도 같은 문서 쌍"""
    n, num_perm = signatures.shape
    rows = num_perm // bands
    pairs = set()
    for b in range(bands):
        buckets: dict[bytes, list[int]] = {}
        for i in range(n):
            buckets.setdefault(signatures[i, b * rows : (b + 1) * rows].tobytes(), []).append(i)
        for members in buckets.values():
            if 1 < len(members) <= 50:
                for x in range(len(members)):
                    for y in range(x + 1, len(members)):
                        pairs.add((members[x], members[y]))
    return pairs


def estimated_jaccard(sig_a: np.ndarray, sig_b: np.ndarray) -> float:
    return float((sig_a == sig_b).mean())
