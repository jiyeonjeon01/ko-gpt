import numpy as np

from cleaning import (MinHasher, estimated_jaccard, filter_code, filter_ko_web, filter_wiki, is_wiki_mirror,
                      lsh_candidate_pairs, mask_pii)

KO = "".join(f"{i}일째 날씨가 맑았다. 우리는 공원에 가서 {i}번째 산책을 했다. 저녁에는 가족과 밥을 먹었다.\n"
             for i in range(5))


def test_pii_masked_as_plain_text():
    text, counts = mask_pii("문의: hong.gd@example.co.kr, 010-1234-5678, 02-123-4567, 900101-1234567")
    assert text == "문의: [EMAIL], [PHONE], [PHONE], [ID_NUMBER]"
    assert counts == {"[EMAIL]": 1, "[PHONE]": 2, "[ID_NUMBER]": 1}
    assert "<|" not in text  # 특수 토큰 형식이 아니다


def test_pii_leaves_ordinary_numbers():
    text, counts = mask_pii("2026년 11월 5일, 인구 9,400,000명, 버전 1.2.3")
    assert counts == {} and "2026" in text


def test_ko_web_filter_reasons():
    assert filter_ko_web(KO + "추가 문장입니다.", "https://example.com/a") is None
    assert filter_ko_web(KO, "https://ko.wikipedia.org/wiki/x") == "wiki_mirror_url"
    assert filter_ko_web("짧다.", None) == "too_short"
    assert filter_ko_web("This is English text. " * 20, None) == "low_hangul_ratio"
    assert filter_ko_web("같은 줄이 반복된다.\n" * 50, None) == "repeated_lines"
    assert filter_ko_web(KO + "카지노 바카라 안내", None) == "spam_terms"


def test_wiki_mirror_domains():
    assert is_wiki_mirror("https://ko.m.wikipedia.org/wiki/a")
    assert is_wiki_mirror("https://www.wikiwand.com/ko/a")
    assert not is_wiki_mirror("https://notwikipedia.org.example.com/")
    assert not is_wiki_mirror(None)


def test_wiki_and_code_filters():
    assert filter_wiki("가" * 400, "사과 (동음이의)", "ko") == "disambiguation"
    assert filter_wiki("x" * 400, "Mercury", "en") is None
    assert filter_code("x = 1\n" * 20) is None
    assert filter_code("# Auto-generated file. Do not edit.\n" + "x = 1\n" * 20) == "autogenerated"


def test_minhash_finds_near_duplicates_only():
    h = MinHasher(num_perm=64)
    base = " ".join(f"{i}번째 문장은 근사 중복 시험을 위한 서로 다른 내용 {i * 7}을 담는다." for i in range(40))
    near = base[:-10] + "조금 바꾼 끝."
    other = " ".join(f"Sentence {i} talks about a totally unrelated topic number {i * 3}." for i in range(40))
    sigs = np.stack([h.signature(t) for t in (base, near, other)])
    assert estimated_jaccard(sigs[0], sigs[1]) > 0.8
    assert estimated_jaccard(sigs[0], sigs[2]) < 0.2
    assert (0, 1) in lsh_candidate_pairs(sigs, bands=16)


def test_minhash_estimate_tracks_true_jaccard():
    # 내용이 다른 문서 쌍을 근사 중복으로 착각하던 버그의 회귀 시험: 추정치가 실제 Jaccard 근처여야 한다
    h = MinHasher(num_perm=256)
    words = [f"단어{i}" for i in range(3000)]
    a = " ".join(words[:600])
    for overlap_start in (0, 150, 300, 450, 600):
        b = " ".join(words[overlap_start : overlap_start + 600])
        sa, sb = set(h.shingles(a)), set(h.shingles(b))
        true = len(sa & sb) / len(sa | sb)
        est = estimated_jaccard(h.signature(a), h.signature(b))
        assert abs(est - true) < 0.1, (overlap_start, true, est)
